// Generates the markdown docs in the repository's `docs` directory from the same endpoint data as the site.
// Run with `npm run generate-docs` from the web directory. The `docs` directory is fully replaced on every run.
import {promises as fs} from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import {createTypeAlias, printNode, zodToTs} from 'zod-to-ts'
import {endpoints, type AugmentedValorantEndpoint} from '../src/types/AugmentedValorantEndpoint'
import {endpointToURL, getRequestHeaders, getSlug, isHttpEndpoint, toCurl} from '../src/lib/request'

const SITE = 'https://valdocs.prometheuz.me'
const REPO = 'https://github.com/PrometheuzzZ/valorant-api-docs'
const docsDir = process.env.DOCS_DIR ?? path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'docs')

const fileHeader = [
    '<!--',
    '',
    'This file is automatically generated from the valorant-api-types package!',
    'Do not edit it directly!',
    `See ${REPO}/blob/trunk/contributing.md for more information.`,
    '',
    '-->',
    '',
    ''
].join('\n')

// Variables whose explanation is shared between many endpoints and lives on the site
const commonVariables = new Map<string, string>([
    ['shard', 'The shard the account was created on: `na`, `pbe`, `eu`, `ap` or `kr`'],
    ['region', 'The region of the account: `na`, `latam`, `br`, `eu`, `ap` or `kr`'],
    ['cluster', 'The SGP cluster: `euc1`, `usw2`, `apse1` or `apne1`'],
    ['port', 'The port from the Riot Client lockfile (`%LocalAppData%\\Riot Games\\Riot Client\\Config\\lockfile`)'],
    ['lockfile password', 'The password from the Riot Client lockfile'],
    ['puuid', 'A player\'s UUID'],
    ['client platform', `See [Client Platform](${SITE}/endpoint/player-mmr#client-platform)`],
    ['client version', `See [Client Version](${SITE}/endpoint/player-mmr#client-version)`],
    ['entitlement token', `Obtained with the [Entitlements Token](entitlements-token) or [Entitlement](entitlement) endpoint`],
    ['auth token', `Obtained with the [Entitlements Token](entitlements-token) endpoint or Riot auth`]
])

function categoryName(endpoint: AugmentedValorantEndpoint) {
    return Array.isArray(endpoint.category) ? endpoint.category.join(' - ') : endpoint.category ?? 'Other'
}

// Characters that aren't allowed in file names on Windows
function safeFileName(str: string) {
    return str.replace(/[<>:"/\\|?*]/g, '_')
}

function endpointFileName(endpoint: AugmentedValorantEndpoint) {
    return safeFileName(`${endpoint.method ?? 'GET'} ${endpoint.name}.md`)
}

function siteURL(endpoint: AugmentedValorantEndpoint) {
    return `${SITE}/endpoint/${getSlug(endpoint.name)}`
}

// Rewrite "[GET Some Endpoint]" references and bare relative links into links to the site
function linkify(text: string) {
    return text
        .replace(/\[(GET|POST|PUT|PATCH|DELETE|WSS|TCP) (.+?)\](?!\()/g, (_, method, name) => `[${method} ${name}](${SITE}/endpoint/${getSlug(name)})`)
        .replace(/\]\(([a-z0-9-]+(#[\w-]+)?)\)/g, (_, slug) => `](${SITE}/endpoint/${slug})`)
}

function typeBlock(schema: Parameters<typeof zodToTs>[0], name: string) {
    try {
        return '```ts\n' + printNode(createTypeAlias(zodToTs(schema, name).node, name)) + '\n```'
    } catch {
        return '_Unable to render this type, see the website._'
    }
}

function renderEndpoint(endpoint: AugmentedValorantEndpoint) {
    const typeName = endpoint.name.replace(/[^\w]/g, '')
    const lines: string[] = [
        `# ${endpoint.method ?? 'GET'} ${endpoint.name}`,
        '',
        `> View on the website: <${siteURL(endpoint)}>`,
        '',
        linkify(endpoint.description),
        '',
        `Method: \`${endpoint.method ?? 'GET'}\`  `,
        `URL: \`${endpointToURL(endpoint)}\`  `
    ]
    if(endpoint.queryName !== undefined) lines.push(`Internal name: \`${endpoint.queryName}\`  `)

    const headers = getRequestHeaders(endpoint)
    if(endpoint.riotRequirements?.localAuth) headers.push(['Authorization', 'Basic {base64 encoded "riot:{lockfile password}"}'])
    if(headers.length > 0) {
        lines.push('', '## Headers', '')
        for(const [name, value] of headers) lines.push(`- \`${name}: ${value}\``)
    }

    const variables = new Map<string, string | undefined>()
    for(const [, name] of `${endpointToURL(endpoint)} ${headers.map(h => h[1]).join(' ')}`.matchAll(/\{([^}]+)\}/g)) {
        variables.set(name, endpoint.variables?.get(name)?.description ?? commonVariables.get(name))
    }
    for(const [name, type] of endpoint.variables ?? []) {
        if(!variables.has(name)) variables.set(name, type.description)
    }
    if(variables.size > 0) {
        lines.push('', '## Variables', '')
        for(const [name, description] of variables) {
            lines.push(`- \`{${name}}\`` + (description ? `: ${linkify(description.replace(/\n+/g, ' '))}` : ''))
        }
    }

    if(endpoint.query !== undefined && endpoint.query.size > 0) {
        lines.push('', '## Query Parameters', '')
        for(const [name, type] of endpoint.query) {
            lines.push(`- \`${name}\` (${type.isOptional() ? 'optional' : 'required'})` + (type.description ? `: ${linkify(type.description.replace(/\n+/g, ' '))}` : ''))
        }
    }

    if(isHttpEndpoint(endpoint)) {
        lines.push('', '## Example Request', '', '```sh', toCurl(endpoint), '```')
    }

    if(endpoint.body !== undefined) {
        lines.push('', '## Body', '', typeBlock(endpoint.body, `${typeName}Body`))
    }

    if(endpoint.responses?.['200'] !== undefined) {
        lines.push('', '## Response', '', typeBlock(endpoint.responses['200'], `${typeName}Response`))
    }

    return lines.join('\n') + '\n'
}

function tableCell(str: string) {
    return str.split('\n')[0].replaceAll('|', '\\|').trim()
}

function encodeLink(str: string) {
    return str.split('/').map(encodeURIComponent).join('/')
}

async function main() {
    await fs.rm(docsDir, {recursive: true, force: true})
    await fs.mkdir(docsDir, {recursive: true})

    const categories = new Map<string, AugmentedValorantEndpoint[]>()
    for(const endpoint of Object.values(endpoints)) {
        const category = categoryName(endpoint)
        if(!categories.has(category)) categories.set(category, [])
        categories.get(category)!.push(endpoint)
    }

    const index = [
        '# Valorant API Docs',
        '',
        `> The full documentation is at <${SITE}>. These markdown files are generated from the same data.`,
        '',
        'These endpoints are **not** officially supported. Use common sense and you won\'t get banned.',
        '',
        `An Insomnia workspace is available at <${SITE}/insomnia.json> and an OpenAPI spec at <${SITE}/openapi.json>.`,
        '',
        '## Categories',
        ''
    ]

    for(const [category, categoryEndpoints] of categories) {
        const categoryDir = path.join(docsDir, safeFileName(category))
        await fs.mkdir(categoryDir, {recursive: true})

        const readme = [`# ${category}`, '', '| Endpoint | Description |', '|---|---|']
        for(const endpoint of categoryEndpoints) {
            const fileName = endpointFileName(endpoint)
            await fs.writeFile(path.join(categoryDir, fileName), fileHeader + renderEndpoint(endpoint), 'utf-8')
            readme.push(`| [${endpoint.method ?? 'GET'} ${endpoint.name}](${encodeLink(fileName)}) | ${tableCell(endpoint.description)} |`)
        }
        await fs.writeFile(path.join(categoryDir, 'readme.md'), fileHeader + readme.join('\n') + '\n', 'utf-8')

        index.push(`- [${category}](${encodeLink(safeFileName(category))}/readme.md) (${categoryEndpoints.length})`)
    }

    await fs.writeFile(path.join(docsDir, 'readme.md'), fileHeader + index.join('\n') + '\n', 'utf-8')
    console.log(`Generated docs for ${Object.keys(endpoints).length} endpoints in ${categories.size} categories`)
}

main()
